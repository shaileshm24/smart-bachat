    def _prepare_transaction_summary(self, transactions: List[TransactionData]) -> str:
        """Prepare transaction summary for AI prompt."""
        if not transactions:
            return "No transaction data available."

        # Calculate totals by category
        income = sum(t.amount for t in transactions if t.direction == "CREDIT")
        expenses = sum(t.amount for t in transactions if t.direction == "DEBIT")

        category_totals = {}
        for t in transactions:
            if t.direction == "DEBIT":
                cat = t.category or "UNCATEGORIZED"
                category_totals[cat] = category_totals.get(cat, 0) + t.amount

        # Sort by amount
        sorted_cats = sorted(category_totals.items(), key=lambda x: x[1], reverse=True)

        lines = [
            f"Total Income: ₹{income:,.0f}",
            f"Total Expenses: ₹{expenses:,.0f}",
            f"Net Savings: ₹{income - expenses:,.0f}",
            f"Savings Rate: {((income - expenses) / income * 100) if income > 0 else 0:.1f}%",
            "",
            "Spending by Category:"
        ]
        for cat, amount in sorted_cats[:10]:
            pct = (amount / expenses * 100) if expenses > 0 else 0
            lines.append(f"  - {cat}: ₹{amount:,.0f} ({pct:.1f}%)")

        return "\n".join(lines)

    def _prepare_goals_context(self, goals: List[GoalData], exclude_id: UUID = None) -> str:
        """Prepare goals context for AI prompt."""
        if not goals:
            return "No goals set."

        lines = []
        for g in goals:
            if exclude_id and g.id == exclude_id:
                continue
            if g.status == "ACTIVE":
                status = "✓ On Track" if g.is_on_track else "⚠ Needs Attention"
                deadline = f", Deadline: {g.deadline}" if g.deadline else ""
                lines.append(
                    f"- {g.name} ({g.goal_type}): ₹{g.current_amount:,.0f}/₹{g.target_amount:,.0f} "
                    f"({g.progress_percent:.0f}%){deadline} - {status}"
                )
        return "\n".join(lines) if lines else "No active goals."

    async def _call_openai(self, prompt: str) -> dict:
        """Call OpenAI API and return parsed JSON response."""
        self.logger.info("=" * 50)
        self.logger.info("OPENAI API CALL STARTED")
        self.logger.info(f"Model: {self.settings.openai_model}")
        self.logger.info(f"Temperature: {self.settings.openai_temperature}")
        self.logger.info(f"Prompt length: {len(prompt)} characters")
        self.logger.debug(f"Full prompt:\n{prompt[:500]}...")  # First 500 chars

        try:
            self.logger.info("Sending request to OpenAI...")
            response = await self.client.chat.completions.create(
                model=self.settings.openai_model,
                messages=[
                    {
                        "role": "system",
                        "content": "You are an expert Indian financial advisor with deep knowledge of personal finance, savings strategies, and Indian financial instruments (SIPs, FDs, RDs, PPF, NPS). Provide accurate, actionable, and encouraging advice. Always respond with valid JSON."
                    },
                    {"role": "user", "content": prompt}
                ],
                temperature=self.settings.openai_temperature,
                max_tokens=2000,
                response_format={"type": "json_object"}
            )

            raw_content = response.choices[0].message.content
            self.logger.info("OPENAI RESPONSE RECEIVED")
            self.logger.info(f"Response length: {len(raw_content)} characters")
            self.logger.info(f"Usage - Prompt tokens: {response.usage.prompt_tokens}, Completion tokens: {response.usage.completion_tokens}")
            self.logger.info(f"Raw response:\n{raw_content}")

            parsed = json.loads(raw_content)
            self.logger.info(f"Parsed JSON keys: {list(parsed.keys())}")
            self.logger.info("=" * 50)

            return parsed
        except json.JSONDecodeError as e:
            self.logger.error(f"JSON parsing error: {e}")
            self.logger.error(f"Raw content that failed to parse: {raw_content}")
            raise Exception(f"AI response parsing error: {str(e)}")
        except Exception as e:
            self.logger.error(f"OpenAI API error: {type(e).__name__}: {e}")
            self.logger.info("=" * 50)
            raise Exception(f"AI service error: {str(e)}")


