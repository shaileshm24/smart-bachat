"""
Fully AI-powered Goal Advisor Service using OpenAI.
All analysis, suggestions, and recommendations are generated by AI.
"""
import json
import logging
from typing import List, Optional
from datetime import date
from uuid import UUID

from openai import AsyncOpenAI
from pydantic import BaseModel

from app.config import get_settings
from app.models.schemas import GoalData, TransactionData


class AIGoalAchievementPlan(BaseModel):
    """AI-generated plan to achieve a goal."""
    goal_id: UUID
    goal_name: str
    current_analysis: str
    achievement_probability: float  # 0-100
    recommended_monthly_saving: float
    time_to_achieve: str  # e.g., "6 months", "1 year"
    spending_cuts: List[dict]  # Categories to cut and amounts
    action_plan: List[str]  # Step-by-step actions
    risks: List[str]  # Potential risks to goal achievement
    motivational_insight: str


class AIGoalSuggestion(BaseModel):
    """AI-suggested goal based on spending analysis."""
    goal_type: str
    suggested_name: str
    suggested_target: float
    suggested_deadline: Optional[str] = None
    why_this_goal: str  # AI explanation
    how_to_achieve: str  # AI strategy
    priority: str
    confidence: float


class AITransactionImpact(BaseModel):
    """AI analysis of transaction impact on goals."""
    transaction_amount: float
    transaction_category: Optional[str]
    is_essential: bool
    impact_level: str  # HIGH, MEDIUM, LOW, NONE
    affected_goals: List[dict]  # Goals affected and how
    ai_verdict: str  # AI's opinion on this transaction
    alternative_suggestion: Optional[str]  # What user could do instead
    savings_opportunity: Optional[float]


class AISpendingWarning(BaseModel):
    """AI warning for unnecessary spending."""
    warning_type: str  # UNNECESSARY, EXCESSIVE, IMPULSE, RECURRING_WASTE
    severity: str  # HIGH, MEDIUM, LOW
    message: str
    affected_goals: List[str]
    potential_savings: float
    recommendation: str


class AIGoalAdvisor:
    """Fully AI-powered goal advisor using OpenAI."""

    def __init__(self):
        self.settings = get_settings()
        self.logger = logging.getLogger(__name__)
        self.client = None
        if self.settings.openai_api_key:
            self.client = AsyncOpenAI(api_key=self.settings.openai_api_key)

    def is_available(self) -> bool:
        return self.client is not None

